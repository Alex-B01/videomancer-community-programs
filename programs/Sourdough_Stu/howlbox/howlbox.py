"""
HOWLBOX -- quarter-wave sine LUT generator (build hook).

Writes ``howlbox_sine_pkg.vhd`` with a single 256-entry quarter-wave sine
magnitude table consumed by ``howlbox.vhd`` for the chroma NCO (Rainbow).

Design notes
------------
* Quarter-wave only: 256 magnitudes covering [0, pi/2). The full circle is
  reconstructed in fabric by quadrant reflection (2 phase MSBs), so the NCO
  needs a single waveform -- no full sin/cos ROM (A3: the 5-EBR sin/cos ROM
  and the 571-LC combinational full LUT are both rejected).
* Read COMBINATIONALLY in howlbox.vhd (concurrent index into this constant),
  so Yosys maps it to distributed LUT4 ROM, NOT an EBR block -> the NCO LUT
  stays 0 EBR and the program's only memory remains the 256x30 remap (2 EBR).
* Magnitude range [0, 511] (9-bit), stored in a 10-bit vector.

Idempotent: same parameters -> byte-identical output each run, so a clean
``git status`` at commit time is the drift check. The Makefile globs
``$(PROJECT_ROOT)/*.vhd`` so the generated package compiles automatically.

Usage
-----
    python3 howlbox.py        # writes howlbox_sine_pkg.vhd alongside this file
"""

from __future__ import annotations

import math
import os

ENTRIES = 256          # quarter-wave resolution (8-bit quarter index)
AMPLITUDE = 511        # peak magnitude (9-bit)
DATA_BITS = 10         # stored width


def quarter_sine() -> list[int]:
    """round(AMPLITUDE * sin(pi/2 * i/ENTRIES)) for i in [0, ENTRIES)."""
    table = []
    for i in range(ENTRIES):
        val = round(AMPLITUDE * math.sin((math.pi / 2.0) * (i / ENTRIES)))
        val = max(0, min(AMPLITUDE, val))
        table.append(val)
    return table


def emit_pkg(table: list[int]) -> str:
    lines = []
    lines.append("-- Copyright (C) 2026 AB (Sourdough_Stu)")
    lines.append("-- SPDX-License-Identifier: GPL-3.0-only")
    lines.append("--")
    lines.append("-- howlbox_sine_pkg.vhd - GENERATED by howlbox.py -- do not edit by hand.")
    lines.append("-- Quarter-wave sine magnitude LUT (256 x 10b, range 0..511) for the")
    lines.append("-- HOWLBOX chroma NCO. Read combinationally in howlbox.vhd (distributed")
    lines.append("-- LUT ROM, 0 EBR); full circle via quadrant reflection in fabric.")
    lines.append("")
    lines.append("library ieee;")
    lines.append("use ieee.std_logic_1164.all;")
    lines.append("use ieee.numeric_std.all;")
    lines.append("")
    lines.append("package howlbox_sine_pkg is")
    lines.append("")
    lines.append(f"  constant C_SINE_ENTRIES : integer := {ENTRIES};")
    lines.append("")
    lines.append(
        "  type t_sine_quarter is array (0 to C_SINE_ENTRIES - 1) "
        f"of std_logic_vector({DATA_BITS - 1} downto 0);"
    )
    lines.append("")
    lines.append("  constant C_SINE_QUARTER : t_sine_quarter := (")
    body = []
    for i, v in enumerate(table):
        body.append(f'    {i:3d} => "{v:010b}"')
    lines.append(",\n".join(body))
    lines.append("  );")
    lines.append("")
    lines.append("end package howlbox_sine_pkg;")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    table = quarter_sine()
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "howlbox_sine_pkg.vhd")
    with open(out_path, "w") as f:
        f.write(emit_pkg(table))
    print(f"wrote {out_path} ({ENTRIES} entries, peak {AMPLITUDE})")


if __name__ == "__main__":
    main()
