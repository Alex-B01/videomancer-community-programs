"""
WITNESS -- build hook: bakes the read-only LUT/ROM packages consumed by the
fabric (HOWLBOX howlbox.py precedent).

Emits two packages next to this file:

  witness_sine_pkg.vhd   -- 256-entry quarter-wave sine magnitude LUT (10b,
                            0..511). RINGS zone-plate sin(k*r^2) + the stamp
                            orbit offsets are reconstructed from it by quadrant
                            reflection in fabric. Read COMBINATIONALLY -> Yosys
                            maps it to distributed LUT ROM (0 EBR).

  witness_stamp_pkg.vhd  -- (a) a 256-entry pre-scaled unit-orbit offset table
                            (cos/sin * C_ORBIT_R, signed 9b) so stamp centres
                            are a table lookup + add (0 multiply); read
                            combinationally (0 EBR).
                            (b) C_STAMP_ROM, a 512x8 sprite ROM holding set A
                            (filled disc) + set B (ring), 16x16 each, address
                            set*256 + row*16 + col. Read REGISTERED in
                            witness_stamp.vhd -> Yosys infers EBR (512x8 = 1-2
                            EBR; hook 6 `found RAM`).

Idempotent: identical parameters -> byte-identical output every run, so a clean
`git status` at commit time is the drift check. build_programs.sh runs this
before `make` (build_programs.sh:405); the Makefile globs $(PROJECT_ROOT)/*.vhd
so the generated packages compile automatically.

Usage:
    python3 witness.py        # writes the two packages alongside this file
"""

from __future__ import annotations

import math
import os

# ---- sine LUT ----
SINE_ENTRIES = 256      # quarter-wave resolution (8-bit quarter index)
SINE_AMP     = 511      # peak magnitude (9-bit, stored 10b)
SINE_BITS    = 10

# ---- stamp orbit + sprite ROM ----
ORBIT_ENTRIES = 256     # full-circle angle resolution
ORBIT_R       = 96      # orbit radius in pixels (pre-scaled into the table)
ORBIT_BITS    = 10      # signed store width for +/-ORBIT_R
SPRITE_N      = 16      # sprite edge (16x16)
ROM_ENTRIES   = 512     # 2 sets x 256 = 512 x 8b  (1 EBR)
ROM_BITS      = 8

HEADER = [
    "-- Copyright (C) 2026 AB (Sourdough_Stu)",
    "-- SPDX-License-Identifier: GPL-3.0-only",
    "--",
]


def quarter_sine() -> list[int]:
    return [max(0, min(SINE_AMP, round(SINE_AMP * math.sin((math.pi / 2.0) * (i / SINE_ENTRIES)))))
            for i in range(SINE_ENTRIES)]


def orbit_tables() -> tuple[list[int], list[int]]:
    xs, ys = [], []
    for i in range(ORBIT_ENTRIES):
        a = 2.0 * math.pi * (i / ORBIT_ENTRIES)
        xs.append(int(round(ORBIT_R * math.cos(a))))
        ys.append(int(round(ORBIT_R * math.sin(a))))
    return xs, ys


def sprite_rom() -> list[int]:
    """set A = filled disc, set B = ring; 16x16, value = alpha/luma 0..255."""
    rom = [0] * ROM_ENTRIES
    c = (SPRITE_N - 1) / 2.0
    r_out = 7.0
    r_in = 4.5
    for row in range(SPRITE_N):
        for col in range(SPRITE_N):
            d = math.hypot(row - c, col - c)
            # set A: filled disc, soft edge
            a = 0
            if d <= r_out:
                a = int(round(255 * max(0.0, min(1.0, (r_out - d) / 2.0 + 0.5))))
            rom[0 * 256 + row * 16 + col] = max(0, min(255, a))
            # set B: ring
            b = 0
            if r_in <= d <= r_out:
                b = 255
            rom[1 * 256 + row * 16 + col] = b
    return rom


def bin_signed(v: int, bits: int) -> str:
    if v < 0:
        v += (1 << bits)
    return format(v & ((1 << bits) - 1), "0{}b".format(bits))


def emit_sine() -> str:
    tab = quarter_sine()
    L = list(HEADER)
    L += [
        "-- witness_sine_pkg.vhd - GENERATED by witness.py -- do not edit by hand.",
        "-- Quarter-wave sine magnitude LUT (256 x 10b, 0..511) for the WITNESS",
        "-- RINGS zone-plate and stamp orbit. Read combinationally (distributed LUT",
        "-- ROM, 0 EBR); full circle via quadrant reflection in fabric.",
        "",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
        "",
        "package witness_sine_pkg is",
        "",
        "  constant C_SINE_ENTRIES : integer := {};".format(SINE_ENTRIES),
        "",
        "  type t_sine_quarter is array (0 to C_SINE_ENTRIES - 1) of "
        "std_logic_vector({} downto 0);".format(SINE_BITS - 1),
        "",
        "  constant C_SINE_QUARTER : t_sine_quarter := (",
    ]
    L.append(",\n".join('    {:3d} => "{}"'.format(i, format(v, "0{}b".format(SINE_BITS)))
                        for i, v in enumerate(tab)))
    L += ["  );", "", "end package witness_sine_pkg;", ""]
    return "\n".join(L)


def emit_stamp() -> str:
    xs, ys = orbit_tables()
    rom = sprite_rom()
    L = list(HEADER)
    L += [
        "-- witness_stamp_pkg.vhd - GENERATED by witness.py -- do not edit by hand.",
        "-- (a) C_ORBIT_XY : 256 x 20b, cos/sin pre-scaled to radius {} px, PACKED as".format(ORBIT_R),
        "--     x = bits[19:10] (signed {}b), y = bits[9:0] (signed {}b). One packed".format(ORBIT_BITS, ORBIT_BITS),
        "--     table -> ONE shared ROM (stamp centre = gaze + one lookup, 0 multiply);",
        "--     witness_stamp.vhd reads it sequentially into 8 registered centres.",
        "-- (b) C_STAMP_ROM : 512 x 8b sprite ROM, set A (disc) + set B (ring),",
        "--     16x16 each, addr = set*256 + row*16 + col. Read REGISTERED in",
        "--     witness_stamp.vhd -> EBR (hook 6 `found RAM`).",
        "",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
        "",
        "package witness_stamp_pkg is",
        "",
        "  constant C_ORBIT_ENTRIES : integer := {};".format(ORBIT_ENTRIES),
        "  constant C_ORBIT_R       : integer := {};".format(ORBIT_R),
        "  constant C_ORBIT_BITS    : integer := {};".format(ORBIT_BITS),
        "  constant C_SPRITE_N      : integer := {};".format(SPRITE_N),
        "  constant C_ROM_ENTRIES   : integer := {};".format(ROM_ENTRIES),
        "",
        "  type t_orbit is array (0 to C_ORBIT_ENTRIES - 1) of "
        "std_logic_vector({} downto 0);".format(2 * ORBIT_BITS - 1),
        "  type t_stamp_rom is array (0 to C_ROM_ENTRIES - 1) of "
        "std_logic_vector({} downto 0);".format(ROM_BITS - 1),
        "",
        "  constant C_ORBIT_XY : t_orbit := (",
    ]
    L.append(",\n".join('    {:3d} => "{}{}"'.format(i, bin_signed(xs[i], ORBIT_BITS), bin_signed(ys[i], ORBIT_BITS))
                        for i in range(ORBIT_ENTRIES)))
    L += ["  );", "", "  constant C_STAMP_ROM : t_stamp_rom := ("]
    L.append(",\n".join('    {:3d} => "{}"'.format(i, format(v, "0{}b".format(ROM_BITS))) for i, v in enumerate(rom)))
    L += ["  );", "", "end package witness_stamp_pkg;", ""]
    return "\n".join(L)


def main() -> None:
    here = os.path.dirname(os.path.abspath(__file__))
    for name, text in (("witness_sine_pkg.vhd", emit_sine()),
                       ("witness_stamp_pkg.vhd", emit_stamp())):
        with open(os.path.join(here, name), "w") as f:
            f.write(text)
        print("wrote", name)


if __name__ == "__main__":
    main()
