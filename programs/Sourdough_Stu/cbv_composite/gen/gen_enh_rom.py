lines.append("--\n-- Credits: Syntonie CBV001 Rev C schematic (CC BY-SA 4.0), Phil Baljeu's Archer trace.")
lines.append("-- Behavioural model only; no schematic artwork is copied.")
lines.append("--\n-- C_ENH(row * 128 + i) = round(v_in(32 i - 1024 cv) / 8), s10, row 0..31 (Enhance), i 0..127.")
lines.append("-" * 80)
lines.append("package cbv_enh_rom_pkg is")
lines.append("  type t_enh_rom is array (0 to 4095) of integer range -512 to 511;")
lines.append("  constant C_ENH : t_enh_rom := (")
rows = [", ".join(str(v) for v in rom[k:k + 16]) for k in range(0, 4096, 16)]
lines.append(",\n".join("    " + r for r in rows) + ");")
lines.append("end package cbv_enh_rom_pkg;\n")
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "cbv_03_enh_rom_pkg.vhd")
open(out, "w").write("\n".join(lines))
print("wrote", os.path.normpath(out), "min", min(rom), "max", max(rom))
