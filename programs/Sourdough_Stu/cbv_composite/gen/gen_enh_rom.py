lines.append("-- Copyright (C) 2026 Sourdough Stu\n-- SPDX-License-Identifier: GPL-3.0-only\n--")
lines.append("-- File: cbv_03_enh_rom_pkg.vhd - CBV Composite Enhance ROM (spec rev 4.1 §5.3)")
lines.append("-- GENERATED by gen/gen_enh_rom.py -- do not edit.")
lines.append("--\n-- This file is free software: you can redistribute it and/or modify it under the terms of the")
lines.append("-- GNU General Public License as published by the Free Software Foundation, either version 3 of")
