"""Generate ../cbv_03_enh_rom_pkg.vhd: the CBV Composite Enhance ROM (spec rev 4.1 §5.3).

ROM[r][i] = round(v_in(x_i) / 8) as s10, x_i = 32 i - 1024 cv (white 0.714 V = 1024 cv),
v_in = the 2N7000 Enhance node solved at x_i (re-implementation of cbv2.enhance_lut, vth = 2.1, Rev C,
identical to plans/cbv_composite/probes/cell_smoke/gen_tables.py), enh_r = ease_mid(r/31, 0.15, 0.85, 2).
Circuit facts: Syntonie CBV001 Rev C schematic (CC BY-SA 4.0), Phil Baljeu's Archer trace.
usage: python3 gen_enh_rom.py   (writes the package next to the program sources)
"""
import math, os

def enh_node(x, e, vth=2.1):
    vg = 3.0 - 1.2 * e
    kp = 0.2
    def I(V):
        if V >= 0:
            vov = vg - vth
            if vov <= 0: return 0.0
            return kp * (vov * V - V * V / 2) if V < vov else kp / 2 * vov * vov
        Vn = -V; vov = vg - V - vth; i = 0.0
        if vov > 0: i = kp * (vov * Vn - Vn * Vn / 2) if Vn < vov else kp / 2 * vov * vov
        i += 1e-12 * (math.exp(min(Vn / 0.031, 60)) - 1)
        return -i
    a, b = -2.5, 2.5
    for _ in range(50):
        m = (a + b) / 2
        if (2 * x - m) / 75 - I(m) - m / 4300 > 0: a = m
        else: b = m
    return m

def ease_mid(k, lo, hi, gamma=2.0):
    t = 2 * k - 1
    return 0.5 * (lo + hi) + 0.5 * (hi - lo) * (1 if t >= 0 else -1) * abs(t) ** gamma

def rnd(z): return int(math.floor(z + 0.5))

rom = []
for r in range(32):
    e = ease_mid(r / 31.0, 0.15, 0.85, 2.0)
    for i in range(128):
        x = (-1024 + 32 * i) * 0.714 / 1024.0
        cv = enh_node(x, e) * 1024.0 / 0.714
        rom.append(max(-512, min(511, rnd(cv / 8.0))))

